const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../static/app.js'), 'utf8');
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function clientComputeOU('), source.indexOf('function updateAHFromMatrix(')), context);
const matrix = [[0, 0, 1], [0, 0, 0], [0, 0, 0]];
const integer = context.clientComputeOU(matrix, 2);
assert.equal(integer.over, 0);
assert.equal(integer.under, 0);
assert.equal(integer.push, 1);
const quarter = context.clientComputeOU(matrix, 2.25);
assert.equal(quarter.over, 0);
assert.equal(quarter.under, 0.5);
assert.equal(quarter.push, 0.5);
console.log('Client O/U integer and quarter settlement semantics passed');
